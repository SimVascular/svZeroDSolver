"""Exact derivatives of the chamber models for svZeroDSolver, with SymPy.

Prints C++ code for

- `kinematics`: the second derivatives d2E/dxi_k dxi_m of the Green-Lagrange
  strain of ChamberCylinder with respect to its local kinematic quantities
  xi = [rho, rho', phi', beta, eps, eta'] (and checks the first derivatives
  of the block against C(xi));
- `material`: the gradient and Hessian of the mooney_rivlin_exponential
  energy in its isochoric invariants;
- `active_stress <yaml>`: the residuals R and the Jacobians dR/da, dR/dadot,
  dR/dlambda of an active stress law, from the same YAML format as
  jacobian.py (whose model loading and differentiation it uses). The fiber
  stretch is the last variable, `lam`.

Usage: python scripts/chamber_tangents.py kinematics|material|active_stress <yaml>
"""
import argparse
import os
import sys

from sympy import Matrix, cse, diff, exp, eye, simplify, symbols, zeros
from sympy.printing import ccode

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import jacobian  # noqa: E402


def kinematics():
    rho, drho, dphi, beta, eps, deta, R = symbols("rho drho dphi beta eps deta R", real=True)
    xi = [rho, drho, dphi, beta, eps, deta]
    a, b, e = 1 + drho, 1 + rho / R, 1 + eps
    # right Cauchy-Green tensor in the (e_R, e_Th, e_Z) basis (genet23 Eqs. 13-16)
    C = Matrix([[a**2 + (R * b * dphi)**2 + deta**2, R * b**2 * dphi, R**2 * b**2 * dphi * beta + deta * e],
                [R * b**2 * dphi, b**2, R * b**2 * beta],
                [R**2 * b**2 * dphi * beta + deta * e, R * b**2 * beta, (R * b * beta)**2 + e**2]])
    E = (C - eye(3)) / 2
    dE = [E.diff(x) for x in xi]
    # first derivatives as coded in ChamberCylinder (compute_kinematics)
    coded = [zeros(3, 3) for _ in range(6)]
    coded[0][0, 0], coded[0][1, 1], coded[0][2, 2] = R * b * dphi**2, b / R, R * b * beta**2
    coded[0][0, 1] = coded[0][1, 0] = b * dphi
    coded[0][0, 2] = coded[0][2, 0] = R * b * dphi * beta
    coded[0][1, 2] = coded[0][2, 1] = b * beta
    coded[1][0, 0] = a
    coded[2][0, 0] = R**2 * b**2 * dphi
    coded[2][0, 1] = coded[2][1, 0] = R * b**2 / 2
    coded[2][0, 2] = coded[2][2, 0] = R**2 * b**2 * beta / 2
    coded[3][2, 2] = R**2 * b**2 * beta
    coded[3][0, 2] = coded[3][2, 0] = R**2 * b**2 * dphi / 2
    coded[3][1, 2] = coded[3][2, 1] = R * b**2 / 2
    coded[4][2, 2] = e
    coded[4][0, 2] = coded[4][2, 0] = deta / 2
    coded[5][0, 0] = deta
    coded[5][0, 2] = coded[5][2, 0] = e / 2
    for k in range(6):
        assert simplify(dE[k] - coded[k]) == zeros(3, 3), f"dE/dxi_{k} differs from the block"
    print("// dE/dxi_k of the block agree with C(xi)")
    # second derivatives (symmetric in k, m), upper triangle of each tensor
    entries = []
    for k in range(6):
        for m in range(k, 6):
            d2 = dE[k].diff(xi[m])
            for i in range(3):
                for j in range(i, 3):
                    if d2[i, j] != 0:
                        entries.append((k, m, i, j, simplify(d2[i, j])))
    subs, reduced = cse([x[-1] for x in entries], symbols=(symbols(f"t{i}") for i in range(100)))
    print("  const double rho = xi[0], dphi = xi[2], beta = xi[3], deta = xi[5];")
    print("  const double b = 1.0 + rho / R;")
    for s, v in subs:
        print(f"  const double {s} = {ccode(v.subs({1 + rho / R: symbols('b')}))};")
    for (k, m, i, j, _), v in zip(entries, reduced):
        expr = ccode(v.subs({1 + rho / R: symbols("b")}))
        print(f"  dd[{k}][{m}]({i}, {j}) = {expr};")


def material():
    I1, I2, I4, W1, W2, C0, C1, C2, C3 = symbols("I1b I2b I4b W1 W2 C0 C1 C2 C3", real=True)
    W = W1 * (I1 - 3) + W2 * (I2 - 3) + C0 * exp(C1 * (I1 - 3)**2) + C2 * exp(C3 * (I4 - 1)**2)
    inv = [I1, I2, I4]
    print("// gradient dW/dI")
    for i, x in enumerate(inv):
        print(f"w[{i}] = {ccode(simplify(diff(W, x)))};")
    print("// Hessian d2W/dI dI (nonzero entries)")
    for i, x in enumerate(inv):
        for j, y in enumerate(inv):
            if j >= i:
                h = simplify(diff(W, x, y))
                if h != 0:
                    print(f"h[{i}][{j}] = {ccode(h)};")


def active_stress(path):
    y, dy, constants, residuals, _, _, _, func_subs = jacobian.load_model(path)
    E, F = jacobian.extract_linear(residuals, y, dy)
    C, dC_dy, dC_dydot = jacobian.extract_nonlinear(residuals, E, F, y, dy)
    R, J_y, J_dy = jacobian.resolve_strain_dependent_functions(
        [simplify(E * dy + F * y + C), F + dC_dy, E + dC_dydot], func_subs)
    n = len(residuals)
    assert len(y) == n + 1 and str(y[-1]) == "lam", "the variables are the n states and lam"
    print(f"  // generated by scripts/chamber_tangents.py active_stress {os.path.basename(path)}")
    for i, s in enumerate(y[:-1]):
        print(f"  const double {s} = a[{i}], {dy[i]} = adot[{i}];")
    print("  const double lam = lambda;")
    exprs, names = [], []
    for i in range(n):
        exprs.append(R[i]), names.append(f"lin.R[{i}]")
        for j in range(n):
            for mat, target in ((J_y, "dR_da"), (J_dy, "dR_dadot")):
                if mat[i, j] != 0:
                    exprs.append(mat[i, j]), names.append(f"lin.{target}[{i * n + j}]")
        if J_y[i, n] != 0:
            exprs.append(J_y[i, n]), names.append(f"lin.dR_dlambda[{i}]")
    subs, reduced = cse(exprs, symbols=(symbols(f"t{i}") for i in range(200)))
    for s, v in subs:
        print(f"  const double {s} = {ccode(v)};")
    for name, v in zip(names, reduced):
        print(f"  {name} = {ccode(v)};")
    print("  // constants used:", ", ".join(sorted(str(c) for c in
                                                  set().union(*(e.free_symbols for e in exprs))
                                                  if c in set(constants))))


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("part", choices=["kinematics", "material", "active_stress"])
    ap.add_argument("yaml_file", nargs="?")
    a = ap.parse_args()
    if a.part == "kinematics":
        kinematics()
    elif a.part == "material":
        material()
    else:
        active_stress(a.yaml_file)
